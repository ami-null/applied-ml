# Run Rscript digits.R from figures/digits.
source("../../../12_dimensionality-reduction_pca/figures/helpers.R")
data_dir <- "../../../12_dimensionality-reduction_pca/figures/digits/data"
read_digits <- function(file) {
    raw <- read.csv(file.path(data_dir, file), header = FALSE)
    stopifnot(ncol(raw) == 65, all(raw[, 65] %in% 0:9))
    list(x = as.matrix(raw[, 1:64]) / 16, y = raw[, 65])
}

seed <- 1301
set.seed(seed)
train <- read_digits("optdigits.tra")
by_digit <- split(seq_along(train$y), train$y)
fit <- sort(unlist(lapply(by_digit, function(rows) sample(rows, round(0.8 * length(rows))))))
valid <- setdiff(seq_along(train$y), fit)
labels <- 0:9
baseline_data <- data.frame(label = factor(train$y[fit], levels = labels), train$x[fit, ])
baseline <- nnet::multinom(label ~ ., data = baseline_data, decay = 0.01,
                           maxit = 1000, trace = FALSE)
stopifnot(baseline$convergence == 0)

# Last row in each weight matrix holds the biases.
with_bias <- function(x) cbind(x, 1)
forward <- function(x, hidden_weights, output_weights) {
    hidden <- x %*% hidden_weights
    hidden <- pmax(hidden, 0)
    logits <- with_bias(hidden) %*% output_weights
    shifted <- logits - apply(logits, 1, max)
    exp_scores <- exp(shifted)
    list(hidden = hidden, prob = exp_scores / rowSums(exp_scores))
}

cross_entropy <- function(prob, y) {
    observed <- prob[cbind(seq_along(y), y + 1L)]
    -mean(log(pmax(observed, .Machine$double.xmin)))
}

x <- with_bias(train$x)
width <- 32
batch_size <- 64
epochs <- 100
rate <- 0.05
momentum <- 0.9
hidden_weights <- rbind(matrix(rnorm(64 * width, sd = sqrt(2 / 64)), 64), 0)
output_weights <- rbind(matrix(rnorm(width * 10, sd = sqrt(1 / width)), width), 0)
hidden_step <- 0 * hidden_weights
output_step <- 0 * output_weights
targets <- diag(10)[train$y + 1L, ]
history <- data.frame(epoch = seq_len(epochs), fitting = NA_real_, validation = NA_real_)
best_loss <- Inf

for (epoch in seq_len(epochs)) {
    order <- sample(fit)
    batches <- split(order, ceiling(seq_along(order) / batch_size))
    for (rows in batches) {
        batch <- x[rows, , drop = FALSE]
        pass <- forward(batch, hidden_weights, output_weights)
        output_error <- (pass$prob - targets[rows, ]) / length(rows)
        hidden_error <- (output_error %*% t(output_weights[seq_len(width), ])) *
            (pass$hidden > 0)
        output_step <- momentum * output_step - rate * crossprod(with_bias(pass$hidden), output_error)
        hidden_step <- momentum * hidden_step - rate * crossprod(batch, hidden_error)
        output_weights <- output_weights + output_step
        hidden_weights <- hidden_weights + hidden_step
    }
    prob <- forward(x, hidden_weights, output_weights)$prob
    history$fitting[epoch] <- cross_entropy(prob[fit, ], train$y[fit])
    history$validation[epoch] <- cross_entropy(prob[valid, ], train$y[valid])
    if (history$validation[epoch] < best_loss) {
        best_loss <- history$validation[epoch]
        best_hidden <- hidden_weights
        best_output <- output_weights
        best_epoch <- epoch
    }
}

# Evaluate both frozen models on the official test file.
test <- read_digits("optdigits.tes")
linear_prob <- predict(baseline, newdata = as.data.frame(test$x), type = "probs")
stopifnot(identical(colnames(linear_prob), as.character(labels)))
nn_prob <- forward(with_bias(test$x), best_hidden, best_output)$prob
metrics <- function(prob) {
    stopifnot(all(is.finite(prob)), max(abs(rowSums(prob) - 1)) < 1e-9)
    correct <- max.col(prob, ties.method = "first") - 1L == test$y
    c(accuracy = mean(correct), log_loss = cross_entropy(prob, test$y), errors = sum(!correct))
}
prediction <- max.col(nn_prob, ties.method = "first") - 1L
confidence <- apply(nn_prob, 1, max)
confusion <- table(true = factor(test$y, levels = labels), predicted = factor(prediction, levels = labels))
examples <- head(which(prediction != test$y), 3)
if (!length(examples)) examples <- head(order(confidence), 3)
stopifnot(best_epoch == which.min(history$validation), sum(confusion) == length(test$y))

.numbers_file <- "numbers_digits.txt"
writeLines("Lecture 13. UCI optdigits (generated by digits.R)", .numbers_file)
