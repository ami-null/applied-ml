                     paste("ggplot2", packageVersion("ggplot2"))))
report("Split seed", seed, 0)
report("Observations", c(fitting = length(fit), validation = length(valid), test = length(test$y)), 0)
report("Scaling", "pixel / 16")
report("Multinomial logistic regression", "nnet::multinom, decay 0.01, maxit 1000")
report("MLP", "64-32-10, ReLU, softmax, mini-batch SGD with momentum")
report("Training settings", c(rate = rate, momentum = momentum, batch_size = batch_size, epochs = epochs))
report("Trainable parameters", length(best_hidden) + length(best_output), 0)
report("Selected epoch", best_epoch, 0)
report("Selected validation log loss", best_loss, 6)
report("Logistic test metrics", metrics(linear_prob), 6)
report("Network test metrics", metrics(nn_prob), 6)
