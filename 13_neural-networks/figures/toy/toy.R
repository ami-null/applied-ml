source("../../../12_dimensionality-reduction_pca/figures/helpers.R")

forward <- function(x, w11 = 1) {
    z <- c(w11 * x[1], x[2])
    hidden <- pmax(z, 0)
    score <- sum(hidden) - 1
    c(z1 = z[1], z2 = z[2], h1 = hidden[1], h2 = hidden[2],
      score = score, probability = plogis(score), class = as.integer(score > 0))
}

x <- c(2, -1)
loss <- function(w11) -log(forward(x, w11)[["probability"]])
gradient <- (forward(x)[["probability"]] - 1) * x[1]
epsilon <- 1e-5
numeric_gradient <- (loss(1 + epsilon) - loss(1 - epsilon)) / (2 * epsilon)
updated <- 1 - 0.1 * gradient
stopifnot(abs(gradient - numeric_gradient) < 1e-8, loss(updated) < loss(1))

.numbers_file <- "numbers_toy.txt"
writeLines("Lecture 13. Worked network (generated by toy.R)", .numbers_file)
report("Hidden weights and biases", "identity matrix, biases (0, 0)")
report("Output weights and bias", "(1, 1), bias -1")
report("Pass at (2, -1), true class 1", forward(x), 6)
report("Pass at (-1, -1)", forward(c(-1, -1)), 6)
report("Loss if true-class probability is 0.1", -log(0.1), 6)
report("Derivative", c(analytic = gradient, finite_difference = numeric_gradient), 8)
report("Learning rate and updated weight", c(rate = 0.1, w11 = updated), 6)
report("Loss", c(before = loss(1), after = loss(updated)), 6)
report("Updated pass at (2, -1)", forward(x, updated), 6)

axis_values <- seq(-2, 2, length.out = 161)
grid <- expand.grid(x1 = axis_values, x2 = axis_values)
grid$h1 <- pmax(0, grid$x1)
grid$h2 <- pmax(0, grid$x2)
grid$score <- grid$h1 + grid$h2 - 1
plane <- ggplot(grid, aes(x1, x2)) + coord_equal(expand = FALSE) +
    labs(x = expression(x[1]), y = expression(x[2]))
boundary <- geom_contour(aes(z = score), breaks = 0, colour = "black", linewidth = 0.8)
classes <- plane + geom_raster(aes(fill = factor(as.integer(score > 0)))) +
    scale_fill_manual("Class", values = okabe[c(6, 5)])
ggsave("fig_classes.pdf", classes, width = 4.6, height = 4)

relu <- ggplot(data.frame(z = axis_values), aes(z, pmax(0, z))) +
    geom_line(colour = okabe[1], linewidth = 1) + labs(x = "Input score", y = "ReLU output")
ggsave("fig_relu.pdf", relu, width = 4.8, height = 3.4)

maps <- rbind(transform(grid, unit = "Hidden unit 1", activation = h1),
              transform(grid, unit = "Hidden unit 2", activation = h2))
features <- plane + geom_raster(data = maps, aes(fill = activation)) +
    facet_wrap(~unit) + scale_fill_gradient("Activation", low = "white", high = okabe[1]) +
    annotate("point", x = x[1], y = x[2], shape = 21, fill = okabe[5], size = 3)
ggsave("fig_hidden_features.pdf", features, width = 7, height = 3.9)
scores <- plane + geom_raster(aes(fill = score)) + boundary +
    scale_fill_gradient2("Score", low = okabe[6], mid = "white", high = okabe[2])
ggsave("fig_score_boundary.pdf", scores, width = 4.6, height = 4)
