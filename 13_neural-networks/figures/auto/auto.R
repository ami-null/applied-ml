# Run Rscript auto.R from figures/auto.
source("../../../12_dimensionality-reduction_pca/figures/helpers.R")
cars <- ISLR2::Auto[, c("horsepower", "mpg")]
set.seed(1305)
fit_rows <- sample(nrow(cars), floor(0.8 * nrow(cars)))
train <- cars[fit_rows, ]
test <- cars[-fit_rows, ]

# Two ReLUs facing opposite directions share a learned switch point.
features <- function(hp, knot) {
    data.frame(left = pmax(knot - hp, 0), right = pmax(hp - knot, 0))
}
fit_at <- function(knot) {
    lm(mpg ~ left + right, data = cbind(train, features(train$horsepower, knot)))
}
candidates <- sort(unique(train$horsepower))
candidates <- candidates[candidates > min(candidates) & candidates < max(candidates)]
fits <- lapply(candidates, fit_at)
best <- which.min(vapply(fits, deviance, numeric(1)))
knot <- candidates[best]
network <- fits[[best]]
linear <- lm(mpg ~ horsepower, data = train)
quadratic <- lm(mpg ~ horsepower + I(horsepower^2), data = train)
predict_all <- function(hp) {
    new_cars <- data.frame(horsepower = hp)
    data.frame(Linear = unname(predict(linear, new_cars)),
               Quadratic = unname(predict(quadratic, new_cars)),
               Network = unname(predict(network, features(hp, knot))))
}
pred <- predict_all(test$horsepower)
rmse <- sqrt(colMeans((as.matrix(pred) - test$mpg)^2))
.numbers_file <- "numbers_auto.txt"
writeLines("Lecture 13. Auto fuel economy (generated by auto.R)", .numbers_file)
report("Split", c(seed = 1305, training = nrow(train), test = nrow(test)), 0)
report("Learned threshold (horsepower)", knot, 0)
report("Network coefficients", coef(network), 6)
report("Predicted mpg at 100 and 150 horsepower", predict_all(c(100, 150))$Network, 6)
report("Test root mean squared error (mpg)", rmse, 6)
stopifnot(all(is.finite(rmse)), length(coef(network)) == 3)
grid <- seq(min(train$horsepower), max(train$horsepower), length.out = 400)
curves <- stack(predict_all(grid))
curves$horsepower <- rep(grid, 3)
plot <- ggplot(train, aes(horsepower, mpg)) +
    geom_point(size = 0.9, colour = "grey45", alpha = 0.45) +
    geom_vline(xintercept = knot, colour = "grey55", linetype = "dotted") +
    geom_line(data = curves, aes(y = values, colour = ind, linetype = ind), linewidth = 0.9) +
    scale_colour_manual(NULL, values = okabe[c(1, 3, 2)]) +
    scale_linetype_manual(NULL, values = c("dashed", "dotdash", "solid")) +
    labs(x = "Engine power (horsepower)", y = "Fuel economy (miles per gallon)")
ggsave("fig_auto_regression.pdf", plot, width = 5.6, height = 3.6)
