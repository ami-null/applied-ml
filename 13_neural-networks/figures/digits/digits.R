digit_panel <- function(images, captions) {
    pixels <- data.frame(value = as.vector(t(images)), col = rep(1:8, nrow(images) * 8),
                         row = rep(rep(8:1, each = 8), nrow(images)),
                         caption = factor(rep(captions, each = 64), levels = captions))
    ggplot(pixels, aes(col, row, fill = value)) + geom_raster() +
        scale_fill_gradient(low = "white", high = "black", limits = c(0, 1), guide = "none") +
        coord_equal(expand = FALSE) + facet_wrap(~caption, nrow = 1) +
        theme_void(base_size = 12) + theme(strip.text = element_text(margin = margin(b = 5)))
}
